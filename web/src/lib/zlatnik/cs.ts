/** Czech label for a feature op, falling back to the English catalog label. */
export function opLabel(op: string, fallback?: string): string {
  return OP_LABELS[op] || fallback || op
}

export function fieldLabel(label: string): string {
  return FIELD_LABELS[label] || label
}

export function optionLabel(label: string): string {
  return OPTION_LABELS[label] || label
}

export function opHint(op: string, fallback?: unknown): string {
  return OP_HINTS[op] || (typeof fallback === 'string' ? fallback : '')
}
